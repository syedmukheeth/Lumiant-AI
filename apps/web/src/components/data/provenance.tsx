"use client";

import { FileSearch, X } from "lucide-react";
import { Popover } from "radix-ui";

import type { FilterDescription, Provenance } from "@/lib/api";
import { formatTimestamp } from "@/lib/format";

function describe(f: FilterDescription): string {
  if ("any" in f) return `any of (${f.any.map(describe).join(" | ")})`;
  const value = Array.isArray(f.value) ? f.value.join(", ") : f.value === null ? "" : String(f.value);
  return `${f.field} ${f.op.replaceAll("_", " ")} ${value}`.trim();
}

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="grid grid-cols-[7.5rem_1fr] gap-3 border-t border-dashed border-line py-1.5 first:border-t-0">
      <dt className="eyebrow pt-0.5">{label}</dt>
      <dd className="min-w-0 text-[0.8125rem] text-ink-2">{children}</dd>
    </div>
  );
}

/** "Show your work": where a number came from, generated by the API — never written by hand. */
export function ProvenanceButton({ provenance, label = "Source" }: { provenance?: Provenance; label?: string }) {
  if (!provenance) return null;
  const p = provenance;
  return (
    <Popover.Root>
      <Popover.Trigger
        className="inline-flex items-center gap-1 rounded-sm px-1.5 py-0.5 text-xs font-medium text-ink-3 transition-colors hover:bg-surface-2 hover:text-ink"
        aria-label={`${label}: how this was calculated`}
      >
        <FileSearch size={13} aria-hidden />
        {label}
      </Popover.Trigger>
      <Popover.Portal>
        <Popover.Content
          align="end"
          sideOffset={6}
          collisionPadding={12}
          className="z-50 w-[min(28rem,calc(100vw-1.5rem))] rounded-md border border-line-strong bg-surface p-4 shadow-xl"
        >
          <div className="mb-2 flex items-start justify-between gap-4">
            <div>
              <p className="eyebrow">Provenance slip</p>
              <p className="mt-0.5 text-sm font-semibold text-ink">{p.metric ? `${p.metric.id} · v${p.metric.version}` : p.dataset}</p>
            </div>
            <Popover.Close className="rounded-sm p-1 text-ink-3 hover:bg-surface-2" aria-label="Close">
              <X size={14} />
            </Popover.Close>
          </div>
          <dl className="max-h-[60vh] overflow-auto">
            <Row label="Source">
              {p.source_system}
              {p.synthetic && <span className="tape-label ml-2 rounded-[2px] px-1 text-[0.625rem] font-bold">SYNTHETIC</span>}
            </Row>
            <Row label="Objects">
              <span className="figure text-xs">{p.source_objects.join(", ")}</span>
            </Row>
            <Row label="Fields">
              <ul className="space-y-0.5">
                {Object.entries(p.fields).map(([canonical, physical]) => (
                  <li key={canonical} className="figure break-words text-xs">
                    <span className="text-ink">{canonical}</span> ← {physical}
                  </li>
                ))}
              </ul>
            </Row>
            <Row label="Your filters">
              {p.filters.user.length ? (
                <ul className="figure space-y-0.5 text-xs">
                  {p.filters.user.map((f, i) => (
                    <li key={i}>{describe(f)}</li>
                  ))}
                </ul>
              ) : (
                "none"
              )}
            </Row>
            <Row label="Access scope">
              {p.filters.injected.length ? (
                <ul className="figure space-y-0.5 text-xs">
                  {p.filters.injected.map((f, i) => (
                    <li key={i}>{describe(f)} <span className="text-ink-3">(applied by your permissions)</span></li>
                  ))}
                </ul>
              ) : (
                "all warehouses in tenant"
              )}
            </Row>
            {p.auto_grouped.length > 0 && <Row label="Split by">{p.auto_grouped.join(", ")} (never summed across)</Row>}
            {(p.metric?.rule ?? p.rule) && (
              <Row label="Rule">
                {p.metric?.rule ?? p.rule}
                {p.metric && <span className="ml-1 text-ink-3">· status: {p.metric.status}</span>}
              </Row>
            )}
            <Row label="Data as of">{formatTimestamp(p.data_as_of)}</Row>
            <Row label="Result">
              {p.row_count} row{p.row_count === 1 ? "" : "s"}
              {p.truncated && " (truncated)"} · {p.duration_ms} ms · run {formatTimestamp(p.executed_at)}
            </Row>
            {p.sql && (
              <Row label="SQL">
                <details>
                  <summary className="cursor-pointer text-xs text-accent">show generated SQL</summary>
                  <pre className="figure mt-1 max-h-48 overflow-auto whitespace-pre-wrap rounded-sm bg-surface-2 p-2 text-[0.6875rem] leading-snug">{p.sql}</pre>
                </details>
              </Row>
            )}
          </dl>
          <Popover.Arrow className="fill-line-strong" />
        </Popover.Content>
      </Popover.Portal>
    </Popover.Root>
  );
}
