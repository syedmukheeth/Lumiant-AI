import type { NextConfig } from "next";

// FastAPI origin. Browser traffic stays same-origin: /api/* is proxied here, so the httpOnly session
// cookie set by the API works without CORS. Evaluated at build time for `next build`.
const API_ORIGIN = process.env.LUMIANT_API_ORIGIN ?? "http://127.0.0.1:8000";

// Content-Security-Policy. Next.js emits inline bootstrap scripts, so script-src needs 'unsafe-inline' until a
// per-request nonce is adopted (docs/06-operations/PRODUCTION_READINESS.md). Everything else is locked down:
// no plugins, no framing, same-origin connections and forms only. Development needs eval for hot reload.
const dev = process.env.NODE_ENV !== "production";
const CSP = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self'${dev ? " ws: wss:" : ""}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async rewrites() {
    return [{ source: "/api/:path*", destination: `${API_ORIGIN}/api/:path*` }];
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: CSP },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
