"""Application settings with fail-fast validation (ADR-0004)."""

from __future__ import annotations

from enum import StrEnum
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import Field, SecretStr, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

# services/api — config/, data/, var/ and alembic/ are resolved against this directory.
BASE_DIR = Path(__file__).resolve().parents[3]


class AppEnv(StrEnum):
    DEVELOPMENT = "development"
    TEST = "test"
    PRODUCTION = "production"


class AuthMode(StrEnum):
    DEV = "dev"
    OIDC = "oidc"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="LUMIANT_", env_file=BASE_DIR / ".env", extra="ignore", frozen=True)

    app_env: AppEnv = AppEnv.DEVELOPMENT
    auth_mode: AuthMode = AuthMode.DEV
    dev_jwt_secret: SecretStr | None = None
    session_ttl_minutes: int = Field(default=480, ge=5, le=1440)
    cookie_secure: bool = False
    log_level: str = Field(default="INFO", pattern=r"^(DEBUG|INFO|WARNING|ERROR)$")
    tenant_config_dir: Path = BASE_DIR / "config" / "tenants"
    # Client-extract tenants generated by `lumiant-ingest` (e.g. var/private/tenants). Development only (ADR-0008).
    private_tenants_dir: Path | None = None
    # Dev sign-in to customer_extract tenants needs this flag as well as LUMIANT_APP_ENV=development.
    allow_customer_extracts: bool = False
    data_dir: Path = BASE_DIR
    app_db_url: str = f"sqlite:///{(BASE_DIR / 'var' / 'app.db').as_posix()}"
    auto_migrate: bool = True
    rate_limit_enabled: bool = True
    rate_limit_chat_per_min: int = Field(default=20, ge=1)
    rate_limit_query_per_min: int = Field(default=120, ge=1)
    rate_limit_export_per_min: int = Field(default=10, ge=1)
    rate_limit_login_per_min: int = Field(default=10, ge=1)
    # Optional shared store so limits hold across replicas (needs the "redis" extra). Unset = in-process limits.
    rate_limit_redis_url: SecretStr | None = None
    agent_provider: Literal["rules", "anthropic"] = "rules"
    agent_model: str = "claude-opus-5-5"
    anthropic_api_key: SecretStr | None = None

    @model_validator(mode="after")
    def _production_guards(self) -> Settings:
        if self.app_env is AppEnv.PRODUCTION:
            if self.auth_mode is AuthMode.DEV:
                raise ValueError("Development authentication cannot be enabled when LUMIANT_APP_ENV=production")
            if not self.cookie_secure:
                raise ValueError("LUMIANT_COOKIE_SECURE must be true when LUMIANT_APP_ENV=production")
            if self.allow_customer_extracts:
                raise ValueError("LUMIANT_ALLOW_CUSTOMER_EXTRACTS cannot be enabled when LUMIANT_APP_ENV=production")
        if self.private_tenants_dir is not None and self.app_env is not AppEnv.DEVELOPMENT:
            raise ValueError("LUMIANT_PRIVATE_TENANTS_DIR is only allowed when LUMIANT_APP_ENV=development")
        if self.dev_jwt_secret is not None and len(self.dev_jwt_secret.get_secret_value()) < 32:
            raise ValueError("LUMIANT_DEV_JWT_SECRET must be at least 32 characters")
        return self

    @property
    def is_production(self) -> bool:
        return self.app_env is AppEnv.PRODUCTION

    @property
    def dev_auth_enabled(self) -> bool:
        return self.auth_mode is AuthMode.DEV and not self.is_production

    @property
    def customer_extract_login_allowed(self) -> bool:
        return self.dev_auth_enabled and self.app_env is AppEnv.DEVELOPMENT and self.allow_customer_extracts


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    return Settings()
