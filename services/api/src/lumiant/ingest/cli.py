"""`lumiant-ingest sap` — load client SAP exports into a local, git-ignored DuckDB warehouse (ADR-0008).

Output lists counts and check results only, never amounts or codes from the files.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from datetime import date
from pathlib import Path

from lumiant.core.config import BASE_DIR, get_settings
from lumiant.ingest.sap_exports import IntakeError, import_sap_exports, sap_tenant_config, write_tenant_yaml
from lumiant.tenancy.registry import PRIVATE_DATA_PREFIX, TenantConfigError, TenantRegistry, parse_tenant_file

TENANT_ID = re.compile(r"^[a-z0-9][a-z0-9-]{1,40}$")
YAML_HEADER = """CLIENT EXTRACT — confidential, for local analysis only (ADR-0008).
Generated by `lumiant-ingest sap`; lives under services/api/var/private/ (git-ignored). Never commit it.
Value maps use SAP standard meanings until the client confirms its own (docs/07-customer/OPEN_QUESTIONS.md)."""


def run_sap(args: argparse.Namespace) -> int:
    tenant_id: str = args.tenant
    if not TENANT_ID.match(tenant_id):
        print("error: tenant id must be lower-case letters, digits and dashes", file=sys.stderr)
        return 2
    settings = get_settings()
    if tenant_id in TenantRegistry.load(settings.tenant_config_dir).ids():
        print(f"error: '{tenant_id}' is a repository tenant; choose another id", file=sys.stderr)
        return 2
    relative = f"{PRIVATE_DATA_PREFIX}/{tenant_id}/warehouse.duckdb"
    target = BASE_DIR / relative
    manifest_path = target.with_name("manifest.json")
    tenant_dir = settings.private_tenants_dir or BASE_DIR / PRIVATE_DATA_PREFIX / "tenants"
    yaml_path = tenant_dir / f"{tenant_id}.yaml"
    started = time.perf_counter()
    try:
        result = import_sap_exports(
            args.stock,
            args.master,
            tenant_id=tenant_id,
            as_of=args.as_of,
            target=target,
            synthetic=False,
            manifest_path=manifest_path,
        )
    except IntakeError as exc:
        print(f"error in {exc.source}:", file=sys.stderr)
        for problem in exc.problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    config = sap_tenant_config(
        tenant_id=tenant_id,
        display_name=args.display_name,
        data_classification="customer_extract",
        source_system="Client SAP exports (MB52 stock list + material master), loaded locally",
        connection_path=relative,
        plants=result.plants,
        dev_users=[
            {
                "username": f"{tenant_id}.admin",
                "display_name": "Client extract admin",
                "roles": ["super_admin"],
                "warehouses": ["*"],
            },
            {
                "username": f"{tenant_id}.viewer",
                "display_name": "Client extract viewer (no cost access)",
                "roles": ["viewer_no_cost"],
                "warehouses": ["*"],
            },
        ],
    )
    write_tenant_yaml(yaml_path, config, YAML_HEADER)
    try:
        parse_tenant_file(yaml_path)
    except TenantConfigError as exc:
        print(f"error: generated tenant config is invalid: {exc}", file=sys.stderr)
        return 1
    m = result.manifest
    print(
        json.dumps(
            {
                "tenant": tenant_id,
                "seconds": round(time.perf_counter() - started, 1),
                "written": [str(p.relative_to(BASE_DIR)) for p in (target, manifest_path)] + [str(yaml_path)],
                "control_totals_passed": m["control_totals"]["passed"],
                "total_rows_excluded": m["stock_total_rows_excluded"],
                "stock": {k: v for k, v in m["stock"].items() if k != "stock_lines_by_status"},
                "master": {k: v for k, v in m["master"].items() if isinstance(v, int)},
                "reconciliation": {k: v for k, v in m["reconciliation"].items() if isinstance(v, int)},
                "valuation_issues": m["valuation_issues"],
                "next": "development only: LUMIANT_PRIVATE_TENANTS_DIR=var/private/tenants and "
                "LUMIANT_ALLOW_CUSTOMER_EXTRACTS=true, then sign in as " + f"{tenant_id}.admin",
            },
            indent=2,
        )
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="lumiant-ingest", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sap = sub.add_parser("sap", help="SAP MB52-style stock list + material master valuation list (XLSX)")
    sap.add_argument("--stock", type=Path, required=True, help="Warehouse Stocks of Material export")
    sap.add_argument("--master", type=Path, required=True, help="Material Master export")
    sap.add_argument("--tenant", required=True, help="tenant id for the extract, e.g. client-sap")
    sap.add_argument("--as-of", type=date.fromisoformat, required=True, help="date of the extract (YYYY-MM-DD)")
    sap.add_argument("--display-name", default="Client SAP extract (confidential)")
    args = parser.parse_args(argv)
    if args.command == "sap":
        return run_sap(args)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
