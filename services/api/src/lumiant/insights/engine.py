"""Insight feed: a ranked list of things worth a look, built only from deterministic analyses (ADR-0002).

Each rule runs governed queries or an existing analysis, so every figure carries provenance, scope injection and
audit like the dashboard. A rule whose data is not mapped is reported as a gap ("needs movement history") instead of
an insight; a rule the role may not see (values without cost access) is skipped silently. Templates contain only
numbers taken from the results; nothing here is generated by a model.
"""

from __future__ import annotations

import logging
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from decimal import ROUND_HALF_EVEN, Decimal
from typing import Any, Literal

from lumiant.analyses.below_reorder import BelowReorderFilters, run_below_reorder
from lumiant.analyses.concentration import run_concentration
from lumiant.analyses.risks import run_data_quality, run_dormant, run_expiring
from lumiant.auth.permissions import Permission
from lumiant.auth.principal import Principal
from lumiant.core.errors import AppError
from lumiant.costing.engine import present
from lumiant.query.plan import QueryPlan
from lumiant.query.results import to_json_value
from lumiant.query.service import QueryService

log = logging.getLogger("lumiant.insights")
Severity = Literal["critical", "warning", "info"]
_RANK = {"critical": 0, "warning": 1, "info": 2}
PCT = Decimal("0.1")
CACHE_TTL_S = 120.0
_STATUS_LABEL = {
    "quality_inspection": "quality inspection",
    "blocked": "blocked stock",
    "restricted": "restricted-use stock",
    "in_transit": "transit and transfer",
    "returns": "returns",
}

# Which data each gap needs, in the customer's terms (shown when a rule cannot run).
_NEEDS = {
    "below_reorder": "reorder points (e.g. SAP MARC reorder point / safety stock)",
    "excess_stock": "maximum stock levels (e.g. SAP MARC maximum stock level)",
    "dormant": "goods-movement history (e.g. SAP MB51 / MSEG, 24 months)",
    "expiring_lots": "batches with shelf-life dates (e.g. SAP MCHB / MCH1)",
}


@dataclass
class Insight:
    id: str
    severity: Severity
    category: str
    title: str
    detail: str
    ask: str
    metrics: list[dict[str, Any]] = field(default_factory=list)
    link: dict[str, Any] | None = None
    selection: dict[str, str] | None = None
    provenance: dict[str, Any] | None = None
    weight: Decimal = Decimal(0)  # tie-break within a severity (larger first)

    def as_dict(self) -> dict[str, Any]:
        out = {k: v for k, v in self.__dict__.items() if k != "weight"}
        out["metrics"] = [{k: to_json_value(v) for k, v in m.items()} for m in self.metrics]
        return out


def _pct(part: Decimal, whole: Decimal) -> Decimal:
    return (part * 100 / whole).quantize(PCT, rounding=ROUND_HALF_EVEN) if whole else Decimal(0)


def _r2(value: Any) -> Decimal:
    """Display rounding for money in titles and metrics (exact figures stay in the provenance-backed analyses)."""
    return present(Decimal(value), 2)


def _money(cur: str, value: Any) -> dict[str, Any]:
    return {"kind": "money", "currency": cur, "value": _r2(value)}


def _n(count: int, singular: str, plural: str) -> str:
    return f"{count} {singular if count == 1 else plural}"


# ------------------------------------------------------------------------------------------------ rules
def _concentration(q: QueryService, p: Principal) -> list[Insight]:
    res = run_concentration(q, p)
    out = []
    for c in res["currencies"][:2]:
        if not c["complete"] or not c["stocked_items"]:
            continue
        out.append(
            Insight(
                id=f"concentration:{c['currency']}",
                severity="info",
                category="value",
                title=(
                    f"{c['items_for_target']} of {c['stocked_items']} stocked items hold {c['target_pct']}% of the "
                    f"{c['currency']} value"
                ),
                detail=(
                    f"That is {c['items_for_target_pct']}% of stocked items; the top 10 alone hold "
                    f"{c['top10_share_pct']}%. Counting, cycle checks and approvals pay off most on this short list."
                ),
                ask="Which items make up most of the inventory value?",
                metrics=[
                    _money(c["currency"], c["total"]),
                    {"kind": "pct", "label": "Top 10 share", "value": c["top10_share_pct"]},
                ],
                link={"page": "costs"},
                provenance=res["provenance"],
                weight=c["total"],
            )
        )
    return out


def _grouped_value(q: QueryService, p: Principal, field_ref: str, action: str) -> tuple[list[dict[str, Any]], Any]:
    res = q.run_plan(
        QueryPlan.model_validate(
            {
                "dataset": "stock_balance",
                "dimensions": [field_ref],
                "measures": [{"field": "stock_value", "agg": "sum", "alias": "value"}],
                "filters": [{"field": "quantity", "op": "gt", "value": "0"}],
                "order_by": [{"field": "value", "direction": "desc"}],
                "limit": 200,
            }
        ),
        p,
        action=action,
    )
    return res.rows, res.provenance


def _location(q: QueryService, p: Principal) -> list[Insight]:
    mapping = q.mapping(p.tenant_id)
    field_ref, label, kind = (
        ("location_id", "storage location", "location")
        if mapping.field("stock_balance", "location_id") is not None
        else ("warehouse_id", "warehouse", "warehouse")
    )
    rows, prov = _grouped_value(q, p, field_ref, "insight:location_concentration")
    out = []
    for cur in sorted({r["currency"] for r in rows if r.get("currency")}):
        group = [r for r in rows if r.get("currency") == cur and r["value"]]
        total = sum((Decimal(r["value"]) for r in group), Decimal(0))
        if len(group) < 2 or total <= 0:
            continue
        top = group[0]
        share = _pct(Decimal(top["value"]), total)
        if share < 25:
            continue
        out.append(
            Insight(
                id=f"location:{cur}:{top[field_ref]}",
                severity="info",
                category="location",
                title=f"{share}% of the {cur} value sits in {label} {top[field_ref]}",
                detail=f"{len(group)} {label}s hold priced stock; the largest holds {cur} {_r2(top['value'])}.",
                ask=f"What is driving the value in {label} {top[field_ref]}?",
                metrics=[_money(cur, top["value"]), {"kind": "pct", "label": "Share", "value": share}],
                link={"page": "inventory", "filters": {"warehouse": top[field_ref]} if kind == "warehouse" else {}},
                selection={"kind": kind, "id": str(top[field_ref])},
                provenance=prov,
                weight=Decimal(top["value"]),
            )
        )
    return out[:2]


def _stock_status(q: QueryService, p: Principal) -> list[Insight]:
    if q.mapping(p.tenant_id).field("stock_balance", "stock_status") is None:
        return []
    rows, prov = _grouped_value(q, p, "stock_status", "insight:stock_status")
    out = []
    for r in rows:
        status, cur = str(r.get("stock_status") or ""), r.get("currency")
        if status not in _STATUS_LABEL or not cur or not r["value"] or Decimal(r["value"]) <= 0:
            continue
        severity: Severity = "warning" if status in ("blocked", "quality_inspection") else "info"
        out.append(
            Insight(
                id=f"status:{status}:{cur}",
                severity=severity,
                category="availability",
                title=f"{cur} {_r2(r['value'])} is tied up in {_STATUS_LABEL[status]}",
                detail="This stock is on hand but not freely usable until it is released.",
                ask=f"Which items are in {_STATUS_LABEL[status]}?",
                metrics=[_money(cur, r["value"])],
                link={"page": "inventory"},
                selection={"kind": "stock_status", "id": status},
                provenance=prov,
                weight=Decimal(r["value"]),
            )
        )
    return out


def _below_reorder(q: QueryService, p: Principal) -> list[Insight]:
    res = run_below_reorder(q, p, BelowReorderFilters(), limit=1, offset=0)
    s = res.summary or {}
    n = int(s.get("flagged") or 0)
    if not n:
        return []
    return [
        Insight(
            id="below_reorder",
            severity="critical",
            category="supply",
            title=f"{_n(n, 'item–warehouse pair is', 'item–warehouse pairs are')} below their reorder level",
            detail="Below the customer-defined reorder level; check open orders before they run out.",
            ask="Which items are below reorder level?",
            metrics=[{"kind": "count", "label": "Pairs", "value": n}],
            link={"page": "overview"},
            provenance=res.provenance,
            weight=Decimal(n),
        )
    ]


def _excess(q: QueryService, p: Principal) -> list[Insight]:
    res = run_below_reorder(q, p, BelowReorderFilters(), limit=1, offset=0, mode="excess")
    n = int((res.summary or {}).get("flagged") or 0)
    if not n:
        return []
    return [
        Insight(
            id="excess_stock",
            severity="warning",
            category="working capital",
            title=f"{_n(n, 'item–warehouse pair holds', 'item–warehouse pairs hold')} more than their maximum stock",
            detail="Excess stock ties up working capital and storage space.",
            ask="Which items are in excess?",
            metrics=[{"kind": "count", "label": "Pairs", "value": n}],
            link={"page": "risks"},
            provenance=res.provenance,
            weight=Decimal(n),
        )
    ]


def _dormant(q: QueryService, p: Principal) -> list[Insight]:
    res = run_dormant(q, p, days=270, limit=1, offset=0)
    n = int((res.summary or {}).get("flagged") or 0)
    if not n:
        return []
    return [
        Insight(
            id="dormant",
            severity="warning",
            category="working capital",
            title=(
                f"{_n(n, 'stocked item–warehouse pair has', 'stocked item–warehouse pairs have')} "
                "had no issue in 270 days"
            ),
            detail="Candidates for redeployment, return or write-down review.",
            ask="Which items have not moved in 270 days?",
            metrics=[{"kind": "count", "label": "Pairs", "value": n}],
            link={"page": "risks"},
            provenance=res.provenance,
            weight=Decimal(n),
        )
    ]


def _expiring(q: QueryService, p: Principal) -> list[Insight]:
    res = run_expiring(q, p, days=60, limit=1)
    s = res.summary or {}
    expired, soon = int(s.get("expired") or 0), int(s.get("expiring") or 0)
    if not (expired or soon):
        return []
    return [
        Insight(
            id="expiring_lots",
            severity="critical" if expired else "warning",
            category="quality",
            title=(
                f"{_n(expired, 'lot on hand is', 'lots on hand are')} expired and {soon} more "
                f"{'expires' if soon == 1 else 'expire'} within 60 days"
            ),
            detail="Quarantine expired lots and use the expiring ones first.",
            ask="Which lots are nearing expiry?",
            metrics=[
                {"kind": "count", "label": "Expired", "value": expired},
                {"kind": "count", "label": "Within 60 days", "value": soon},
            ],
            link={"page": "risks"},
            provenance=res.provenance,
            weight=Decimal(expired * 1000 + soon),
        )
    ]


def _data_quality(q: QueryService, p: Principal) -> list[Insight]:
    dq = run_data_quality(q, p)
    issues = [c for c in dq["checks"] if c["status"] == "issue" and c.get("count")]
    if not issues:
        return []
    worst = max(issues, key=lambda c: c["count"])
    return [
        Insight(
            id="data_quality",
            severity="warning" if len(issues) > 2 else "info",
            category="data quality",
            title=f"{_n(len(issues), 'data-quality check found', 'data-quality checks found')} gaps",
            detail=f"The largest: {worst['title']} ({worst['count']}).",
            ask="Which items have incomplete master data?",
            metrics=[{"kind": "count", "label": worst["title"], "value": worst["count"]}],
            link={"page": "risks"},
            weight=Decimal(worst["count"]),
        )
    ]


Rule = Callable[[QueryService, Principal], list[Insight]]
RULES: list[tuple[str, Rule, tuple[Permission, ...]]] = [
    ("below_reorder", _below_reorder, ()),
    ("expiring_lots", _expiring, ()),
    ("stock_status", _stock_status, (Permission.COST_READ,)),
    ("excess_stock", _excess, ()),
    ("dormant", _dormant, ()),
    ("concentration", _concentration, (Permission.COST_READ,)),
    ("location", _location, (Permission.COST_READ,)),
    ("data_quality", _data_quality, ()),
]


class InsightService:
    def __init__(self, query: QueryService) -> None:
        self.query = query
        self._cache: dict[tuple[str, ...], tuple[float, dict[str, Any]]] = {}

    def _key(self, p: Principal) -> tuple[str, ...]:
        scope = "*" if p.scope.all else ",".join(sorted(p.scope.ids))
        return (p.tenant_id, scope, ",".join(sorted(x.value for x in p.permissions)))

    def feed(self, principal: Principal, *, fresh: bool = False) -> dict[str, Any]:
        """Same scope + permissions share a cached feed for a short time; every figure is still scope-injected."""
        key = self._key(principal)
        hit = self._cache.get(key)
        if hit and not fresh and time.monotonic() - hit[0] < CACHE_TTL_S:
            self.query.record(principal, "insight:feed", None, "allow", "ok", reason="cache")
            return hit[1]
        insights: list[Insight] = []
        gaps: list[dict[str, str]] = []
        for rule_id, rule, needs in RULES:
            if not all(principal.has(n) for n in needs):
                continue
            try:
                insights.extend(rule(self.query, principal))
            except AppError as exc:
                if exc.code == "analysis_unavailable":
                    gaps.append({"id": rule_id, "message": exc.message, "needs": _NEEDS.get(rule_id, "")})
                elif exc.code not in ("forbidden_field", "field_not_available", "dataset_not_available"):
                    log.warning("insight_rule_failed", extra={"rule": rule_id, "error_code": exc.code})
        insights.sort(key=lambda i: (_RANK[i.severity], -i.weight))
        body = {
            "insights": [i.as_dict() for i in insights],
            "gaps": gaps,
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        self._cache[key] = (time.monotonic(), body)
        return body


